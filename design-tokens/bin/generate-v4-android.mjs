function underscoreId(id) {
  return id.toLowerCase().replace(/[^a-z0-9]+/g, "_");
}

function pascalId(id) {
  return id
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");
}

function colorResName(token) {
  return `plantim_v4_${underscoreId(token)}`;
}

const cap = (s) => s[0].toUpperCase() + s.slice(1);
const lower = (s) => s[0].toLowerCase() + s.slice(1);

// ---------------------------------------------------------------------------
// registry access (grade fallback mirrors v4-render.mjs)
// ---------------------------------------------------------------------------

function gradeLayers(icon, grade) {
  return (icon.grades[grade] ?? icon.grades.base).layers;
}

function gradeSolid(icon, grade) {
  return icon.solid[grade] ?? icon.solid.base;
}

