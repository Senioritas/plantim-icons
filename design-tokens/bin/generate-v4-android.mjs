function main() {
  const registry = JSON.parse(readFileSync(REGISTRY, "utf8"));
  const tokens = registry.tokens;
  const grades = registry.sizes.grades;
  const iconIds = Object.keys(registry.icons).sort();

  const drawableDir = path.join(RES, "drawable");
  const valuesDir = path.join(RES, "values");
  const nightDir = path.join(RES, "values-night");
  for (const dir of [drawableDir, valuesDir, nightDir, KT]) {
    rmSync(dir, { recursive: true, force: true });
    mkdirSync(dir, { recursive: true });
  }

  let drawables = 0;
  let kotlinFiles = 0;
  for (const id of iconIds) {
    const icon = registry.icons[id];
    for (const variant of VARIANTS) {
      const file = path.join(drawableDir, `plantim_${underscoreId(id)}_${variant}.xml`);
      writeFileSync(file, drawableXml(icon, variant, grades.base.strokeWidth, tokens));
      drawables += 1;
    }
    writeFileSync(path.join(KT, `${pascalId(id)}.kt`), iconKotlin(icon, grades, tokens));
    kotlinFiles += 1;
  }

  writeFileSync(path.join(valuesDir, "colors_plantim_v4.xml"), colorsXml(tokens, "light"));
  writeFileSync(path.join(nightDir, "colors_plantim_v4.xml"), colorsXml(tokens, "dark"));
  writeFileSync(path.join(KT, "PlantimIconsV4.kt"), indexKotlin(iconIds, grades));
  kotlinFiles += 1;

  console.log(
    `generate-v4-android: ${iconIds.length} icons -> ${drawables} drawables, ` +
      `${kotlinFiles} Kotlin files, ${Object.keys(tokens).length} color tokens (light+night).`,
  );
}

main();
