function colorsXml(tokens, mode) {
  const lines = [
    `<?xml version="1.0" encoding="utf-8"?>`,
    `<!-- ${GENERATED_NOTE} -->`,
    `<!-- Plantim v4 semantic color tokens (${mode} values). -->`,
    `<resources>`,
  ];
  for (const token of Object.keys(tokens).sort()) {
    lines.push(`    <color name="${colorResName(token)}">${tokens[token][mode]}</color>`);
  }
  lines.push(`</resources>`, ``);
  return lines.join("\n");
}

// ---------------------------------------------------------------------------
// Compose ImageVector Kotlin
// ---------------------------------------------------------------------------

function composeColor(hex) {
  const h = hex.replace("#", "").toUpperCase();
  if (!/^[0-9A-F]{6}$/.test(h)) throw new Error(`unsupported color literal "${hex}"`);
  return `Color(0xFF${h})`;
}

/**
 * Emit path(...) { ... } blocks for one icon variant at one grade.
 * Returns { blocks, usesEvenOdd }.
 */
function composePaths(icon, variant, grade, strokeWidth, tokens) {
  const layers = gradeLayers(icon, grade);
  const blocks = [];
  let usesEvenOdd = false;

  const strokeBlock = (d, colorExpr, width, alpha) => {
    const args = [
      `stroke = SolidColor(${colorExpr})`,
      `strokeLineWidth = ${kf(width)}`,
      `strokeLineCap = StrokeCap.Round`,
      `strokeLineJoin = StrokeJoin.Round`,
    ];
    if (alpha !== undefined) args.push(`strokeAlpha = ${kf(alpha)}`);
    return [
      `        path(`,
      ...args.map((a) => `            ${a},`),
      `        ) {`,
      ...composePathBody(d, "            "),
      `        }`,
    ].join("\n");
  };
  const fillBlock = (d, colorExpr, alpha, evenOdd) => {
    const args = [`fill = SolidColor(${colorExpr})`];
    if (alpha !== undefined) args.push(`fillAlpha = ${kf(alpha)}`);
    if (evenOdd) {
      args.push(`pathFillType = PathFillType.EvenOdd`);
      usesEvenOdd = true;
    }
    return [
      `        path(`,
      ...args.map((a) => `            ${a},`),
      `        ) {`,
      ...composePathBody(d, "            "),
      `        }`,
    ].join("\n");
  };
  const nodeBlock = (node, colorExpr, width, alpha) => {
    const d = nodePathData(node);
    return node.filled ? fillBlock(d, colorExpr, alpha) : strokeBlock(d, colorExpr, width, alpha);
  };

  if (variant === "outline") {
    for (const layer of layers) {
      for (const node of layer.nodes) blocks.push(nodeBlock(node, "Color.Black", strokeWidth));
    }
  } else if (variant === "duotone") {
    const primary = new Set(icon.variants.duotone?.primary ?? [layers[0].name]);
    for (const layer of layers) {
      const alpha = primary.has(layer.name) ? undefined : 0.35;
      for (const node of layer.nodes) {
        blocks.push(nodeBlock(node, "Color.Black", strokeWidth, alpha));
      }
    }
  } else if (variant === "multicolor") {
    const map = icon.variants.multicolor ?? {};
    for (const layer of layers) {
      const token = map[layer.name];
      if (token && !tokens[token]) {
        throw new Error(`${icon.id}: multicolor token "${token}" not in registry tokens`);
      }
      const colorExpr = token ? composeColor(tokens[token].light) : "Color.Black";
      for (const node of layer.nodes) blocks.push(nodeBlock(node, colorExpr, strokeWidth));
    }
  } else if (variant === "solid") {
    const solid = gradeSolid(icon, grade);
    if (solid.mode === "bold") {
      for (const layer of layers) {
        for (const node of layer.nodes) {
          blocks.push(nodeBlock(node, "Color.Black", solid.strokeWidth));
        }
      }
    } else {
      for (const d of solid.paths) blocks.push(fillBlock(d, "Color.Black", undefined, true));
    }
  } else {
    throw new Error(`unknown variant ${variant}`);
  }
  return { blocks, usesEvenOdd };
}

const GRADE_SUFFIX = { base: "", micro: "Micro", display: "Display" };

function iconKotlin(icon, grades, tokens) {
  const pascal = pascalId(icon.id);
  const gradeNames = Object.keys(GRADE_SUFFIX).filter((g) => grades[g]);
  const sections = [];
  let usesEvenOdd = false;

  for (const variant of VARIANTS) {
    for (const grade of gradeNames) {
      const valName = `${pascal}${cap(variant)}${GRADE_SUFFIX[grade]}`;
      const backing = `_${lower(valName)}`;
      const builderFn = `build${valName}`;
      const { blocks, usesEvenOdd: eo } = composePaths(
        icon,
        variant,
        grade,
        grades[grade].strokeWidth,
        tokens,
      );
      usesEvenOdd = usesEvenOdd || eo;
      sections.push(
        [
          `/** \`${icon.id}\` ${variant} variant, ${grade} grade. */`,
          `public val ${valName}: ImageVector`,
          `    get() {`,
          `        ${backing}?.let { return it }`,
          `        return ${builderFn}().also { ${backing} = it }`,
          `    }`,
          ``,
          `private var ${backing}: ImageVector? = null`,
          ``,
          `private fun ${builderFn}(): ImageVector =`,
          `    ImageVector.Builder(`,
          `        name = "${valName}",`,
          `        defaultWidth = 24.dp,`,
          `        defaultHeight = 24.dp,`,
          `        viewportWidth = 24f,`,
          `        viewportHeight = 24f,`,
          `    ).apply {`,
          blocks.join("\n"),
          `    }.build()`,
        ].join("\n"),
      );
    }
  }

  const gradesArg = (variant) => {
    const base = `${pascal}${cap(variant)}`;
    return `PlantimIconGrades(base = ${base}, micro = ${base}Micro, display = ${base}Display)`;
  };
  sections.push(
    [
      `/** All grades and variants of \`${icon.id}\` ("${icon.label}", tier ${icon.tier}). */`,
      `public val ${pascal}: PlantimIconV4`,
      `    get() = PlantimIconV4(`,
      `        id = "${icon.id}",`,
      ...VARIANTS.map((v) => `        ${v} = ${gradesArg(v)},`),
      `    )`,
    ].join("\n"),
  );

  const imports = [
    "androidx.compose.ui.graphics.Color",
    ...(usesEvenOdd ? ["androidx.compose.ui.graphics.PathFillType"] : []),
    "androidx.compose.ui.graphics.SolidColor",
    "androidx.compose.ui.graphics.StrokeCap",
    "androidx.compose.ui.graphics.StrokeJoin",
    "androidx.compose.ui.graphics.vector.ImageVector",
    "androidx.compose.ui.graphics.vector.path",
    "androidx.compose.ui.unit.dp",
  ];
  return [
    `// ${GENERATED_NOTE}`,
    `package com.plantim.icons.v4`,
    ``,
    ...imports.map((imp) => `import ${imp}`),
    ``,
    sections.join("\n\n"),
    ``,
  ].join("\n");
}

function indexKotlin(iconIds, grades) {
  // Grades ordered by their largest rendered size (micro -> base -> display).
  const gradeOrder = Object.entries(grades)
    .map(([name, g]) => ({ name, strokeWidth: g.strokeWidth, max: Math.max(...g.sizes) }))
    .sort((a, b) => a.max - b.max);
  const enumEntries = gradeOrder.map(
    (g) => `    ${cap(g.name)}(${kf(g.strokeWidth)}),`,
  );
  const whenArms = gradeOrder
    .slice(0, -1)
    .map((g) => `        sizeDp <= ${g.max} -> PlantimSizeGrade.${cap(g.name)}`);
  whenArms.push(`        else -> PlantimSizeGrade.${cap(gradeOrder[gradeOrder.length - 1].name)}`);
  const gradeMapArms = gradeOrder.map(
    (g) => `        PlantimSizeGrade.${cap(g.name)} -> ${g.name}`,
  );

  return [
    `// ${GENERATED_NOTE}`,
    `package com.plantim.icons.v4`,
    ``,
    `import androidx.compose.ui.graphics.vector.ImageVector`,
    ``,
    `/** Icon variant styles of the Plantim v4 set. */`,
    `public enum class PlantimVariant {`,
    ...VARIANTS.map((v) => `    ${cap(v)},`),
    `}`,
    ``,
    `/** Optical size grades; strokeWidth is in 24-grid units. */`,
    `public enum class PlantimSizeGrade(public val strokeWidth: Float) {`,
    ...enumEntries,
    `}`,
    ``,
    `/** One variant of one icon across all optical grades. */`,
    `public data class PlantimIconGrades(`,
    `    val base: ImageVector,`,
    `    val micro: ImageVector,`,
    `    val display: ImageVector,`,
    `) {`,
    `    public fun forGrade(grade: PlantimSizeGrade): ImageVector = when (grade) {`,
    ...gradeMapArms,
    `    }`,
    `}`,
    ``,
    `/** One v4 icon: every variant, every grade. */`,
    `public data class PlantimIconV4(`,
    `    val id: String,`,
    ...VARIANTS.map((v) => `    val ${v}: PlantimIconGrades,`),
    `) {`,
    `    public fun forVariant(variant: PlantimVariant): PlantimIconGrades = when (variant) {`,
    ...VARIANTS.map((v) => `        PlantimVariant.${cap(v)} -> ${v}`),
    `    }`,
    ``,
    `    public fun imageVector(variant: PlantimVariant, grade: PlantimSizeGrade): ImageVector =`,
    `        forVariant(variant).forGrade(grade)`,
    `}`,
    ``,
    `/** Index of the generated Plantim v4 icon set. */`,
    `public object PlantimIconsV4 {`,
    ``,
    `    /** All icons, sorted by id. */`,
    `    public val allIcons: List<PlantimIconV4> by lazy(LazyThreadSafetyMode.NONE) {`,
    `        listOf(`,
    ...iconIds.map((id) => `            ${pascalId(id)},`),
    `        )`,
    `    }`,
    ``,
    `    /**`,
    `     * Pick the optical grade for a rendered icon size in dp`,
    `     * (${gradeOrder.map((g) => `${g.name}: ${grades[g.name].sizes.join("/")}`).join(", ")}).`,
    `     */`,
    `    public fun sizeGrade(sizeDp: Int): PlantimSizeGrade = when {`,
    ...whenArms,
    `    }`,
    ``,
    `    public fun byId(id: String): PlantimIconV4? = allIcons.firstOrNull { it.id == id }`,
    `}`,
    ``,
  ].join("\n");
}

