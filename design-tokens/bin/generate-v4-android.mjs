const BLACK = "#FF000000";
const TRANSPARENT = "@android:color/transparent";

function xmlPath(attrs) {
  const lines = ["    <path"];
  for (const [k, v] of attrs) {
    lines.push(`        android:${k}="${v}"`);
  }
  lines[lines.length - 1] += " />";
  return lines.join("\n");
}

function strokePathXml(d, color, strokeWidth, alpha) {
  const attrs = [
    ["pathData", d],
    ["fillColor", TRANSPARENT],
    ["strokeColor", color],
    ["strokeWidth", fmt(strokeWidth)],
    ["strokeLineCap", "round"],
    ["strokeLineJoin", "round"],
  ];
  if (alpha !== undefined) attrs.push(["strokeAlpha", alpha]);
  return xmlPath(attrs);
}

function fillPathXml(d, color, alpha, fillType) {
  const attrs = [
    ["pathData", d],
    ["fillColor", color],
  ];
  if (alpha !== undefined) attrs.push(["fillAlpha", alpha]);
  if (fillType !== undefined) attrs.push(["fillType", fillType]);
  return xmlPath(attrs);
}

/** One stroke-or-dot node in outline/duotone/multicolor semantics. */
function nodeXml(node, color, strokeWidth, alpha) {
  const d = nodePathData(node);
  return node.filled ? fillPathXml(d, color, alpha) : strokePathXml(d, color, strokeWidth, alpha);
}

function drawableXml(icon, variant, baseStrokeWidth, tokens) {
  const layers = gradeLayers(icon, "base");
  const paths = [];
  if (variant === "outline") {
    for (const layer of layers) {
      for (const node of layer.nodes) paths.push(nodeXml(node, BLACK, baseStrokeWidth));
    }
  } else if (variant === "duotone") {
    const primary = new Set(icon.variants.duotone?.primary ?? [layers[0].name]);
    for (const layer of layers) {
      const alpha = primary.has(layer.name) ? undefined : "0.35";
      for (const node of layer.nodes) paths.push(nodeXml(node, BLACK, baseStrokeWidth, alpha));
    }
  } else if (variant === "multicolor") {
    const map = icon.variants.multicolor ?? {};
    for (const layer of layers) {
      const token = map[layer.name];
      if (token && !tokens[token]) {
        throw new Error(`${icon.id}: multicolor token "${token}" not in registry tokens`);
      }
      const color = token ? `@color/${colorResName(token)}` : BLACK;
      for (const node of layer.nodes) paths.push(nodeXml(node, color, baseStrokeWidth));
    }
  } else if (variant === "solid") {
    const solid = gradeSolid(icon, "base");
    if (solid.mode === "bold") {
      for (const layer of layers) {
        for (const node of layer.nodes) paths.push(nodeXml(node, BLACK, solid.strokeWidth));
      }
    } else {
      for (const d of solid.paths) paths.push(fillPathXml(d, BLACK, undefined, "evenOdd"));
    }
  } else {
    throw new Error(`unknown variant ${variant}`);
  }
  return [
    `<?xml version="1.0" encoding="utf-8"?>`,
    `<!-- ${GENERATED_NOTE} -->`,
    `<!-- ${icon.id} / ${variant} / base grade (24 grid). -->`,
    `<vector xmlns:android="http://schemas.android.com/apk/res/android"`,
    `    android:width="24dp"`,
    `    android:height="24dp"`,
    `    android:viewportWidth="24"`,
    `    android:viewportHeight="24">`,
    ...paths,
    `</vector>`,
    ``,
  ].join("\n");
}

