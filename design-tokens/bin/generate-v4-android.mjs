/** Round to 3 decimals and strip trailing zeros (matches the v4 fmt clamp). */
function fmt(n) {
  const r = Math.round(n * 1000) / 1000;
  return Object.is(r, -0) ? "0" : String(r);
}

/** Kotlin float literal: 2 -> "2f", 2.4 -> "2.4f". */
function kf(n) {
  return `${fmt(n)}f`;
}

// ---------------------------------------------------------------------------
// shape -> pathData (VectorDrawable understands only <path>)
// ---------------------------------------------------------------------------

function circlePathData(cx, cy, r) {
  // Two 180-degree arcs; valid SVG path grammar, valid android:pathData.
  return (
    `M${fmt(cx - r)} ${fmt(cy)}` +
    `a${fmt(r)} ${fmt(r)} 0 1 1 ${fmt(2 * r)} 0` +
    `a${fmt(r)} ${fmt(r)} 0 1 1 ${fmt(-2 * r)} 0Z`
  );
}

function linePathData(x1, y1, x2, y2) {
  return `M${fmt(x1)} ${fmt(y1)}L${fmt(x2)} ${fmt(y2)}`;
}

function rectPathData(x, y, w, h, rx) {
  if (!rx || rx <= 0) {
    return `M${fmt(x)} ${fmt(y)}h${fmt(w)}v${fmt(h)}h${fmt(-w)}Z`;
  }
  const r = Math.min(rx, w / 2, h / 2);
  const iw = w - 2 * r;
  const ih = h - 2 * r;
  return (
    `M${fmt(x + r)} ${fmt(y)}` +
    `h${fmt(iw)}` +
    `a${fmt(r)} ${fmt(r)} 0 0 1 ${fmt(r)} ${fmt(r)}` +
    `v${fmt(ih)}` +
    `a${fmt(r)} ${fmt(r)} 0 0 1 ${fmt(-r)} ${fmt(r)}` +
    `h${fmt(-iw)}` +
    `a${fmt(r)} ${fmt(r)} 0 0 1 ${fmt(-r)} ${fmt(-r)}` +
    `v${fmt(-ih)}` +
    `a${fmt(r)} ${fmt(r)} 0 0 1 ${fmt(r)} ${fmt(-r)}Z`
  );
}

function nodePathData(node) {
  const a = node.attrs;
  switch (node.type) {
    case "path":
      return a.d;
    case "circle":
      return circlePathData(Number(a.cx), Number(a.cy), Number(a.r));
    case "line":
      return linePathData(Number(a.x1), Number(a.y1), Number(a.x2), Number(a.y2));
    case "rect":
      return rectPathData(
        Number(a.x),
        Number(a.y),
        Number(a.width),
        Number(a.height),
        a.rx === undefined ? 0 : Number(a.rx),
      );
    default:
      throw new Error(`unsupported node type "${node.type}"`);
  }
}

// ---------------------------------------------------------------------------
// SVG path parser -> absolute M/L/C/Q/Z command list (arcs become cubics)
// ---------------------------------------------------------------------------

function vectorAngle(ux, uy, vx, vy) {
  const dot = ux * vx + uy * vy;
  const len = Math.sqrt((ux * ux + uy * uy) * (vx * vx + vy * vy));
  let ang = Math.acos(Math.min(1, Math.max(-1, dot / len)));
  if (ux * vy - uy * vx < 0) ang = -ang;
  return ang;
}

/** W3C SVG F.6.5 endpoint->center parameterization + per-quadrant cubics. */
function arcToCubics(px, py, rx, ry, xRotDeg, largeArc, sweep, x, y) {
  if (rx === 0 || ry === 0 || (px === x && py === y)) {
    return [{ c: "L", x, y }];
  }
  rx = Math.abs(rx);
  ry = Math.abs(ry);
  const phi = (xRotDeg * Math.PI) / 180;
  const cosP = Math.cos(phi);
  const sinP = Math.sin(phi);
  const dx = (px - x) / 2;
  const dy = (py - y) / 2;
  const x1p = cosP * dx + sinP * dy;
  const y1p = -sinP * dx + cosP * dy;
  const lam = (x1p * x1p) / (rx * rx) + (y1p * y1p) / (ry * ry);
  if (lam > 1) {
    const s = Math.sqrt(lam);
    rx *= s;
    ry *= s;
  }
  const den = rx * rx * y1p * y1p + ry * ry * x1p * x1p;
  const num = rx * rx * ry * ry - den;
  let coef = Math.sqrt(Math.max(0, num / den));
  if (largeArc === sweep) coef = -coef;
  const cxp = (coef * (rx * y1p)) / ry;
  const cyp = (-coef * (ry * x1p)) / rx;
  const cx = cosP * cxp - sinP * cyp + (px + x) / 2;
  const cy = sinP * cxp + cosP * cyp + (py + y) / 2;
  const theta1 = vectorAngle(1, 0, (x1p - cxp) / rx, (y1p - cyp) / ry);
  let dTheta = vectorAngle(
    (x1p - cxp) / rx,
    (y1p - cyp) / ry,
    (-x1p - cxp) / rx,
    (-y1p - cyp) / ry,
  );
  if (!sweep && dTheta > 0) dTheta -= 2 * Math.PI;
  if (sweep && dTheta < 0) dTheta += 2 * Math.PI;

  const segs = Math.max(1, Math.ceil(Math.abs(dTheta) / (Math.PI / 2)));
  const delta = dTheta / segs;
  const t = (4 / 3) * Math.tan(delta / 4);
  const point = (a) => [
    cx + rx * Math.cos(a) * cosP - ry * Math.sin(a) * sinP,
    cy + rx * Math.cos(a) * sinP + ry * Math.sin(a) * cosP,
  ];
  const deriv = (a) => [
    -rx * Math.sin(a) * cosP - ry * Math.cos(a) * sinP,
    -rx * Math.sin(a) * sinP + ry * Math.cos(a) * cosP,
  ];

  const out = [];
  let th = theta1;
  let [prevX, prevY] = [px, py];
  for (let i = 0; i < segs; i += 1) {
    const th2 = th + delta;
    const [d1x, d1y] = deriv(th);
    const [d2x, d2y] = deriv(th2);
    const [ex, ey] = point(th2);
    out.push({
      c: "C",
      x1: prevX + t * d1x,
      y1: prevY + t * d1y,
      x2: ex - t * d2x,
      y2: ey - t * d2y,
      x: ex,
      y: ey,
    });
    th = th2;
    prevX = ex;
    prevY = ey;
  }
  const last = out[out.length - 1];
  last.x = x;
  last.y = y;
  return out;
}

/**
 * Parse an SVG path string into absolute commands:
 *   {c:"M",x,y} {c:"L",x,y} {c:"C",x1,y1,x2,y2,x,y} {c:"Q",x1,y1,x,y} {c:"Z"}
 * Supports M/L/H/V/C/S/Q/T/A/Z in both cases; arcs are converted to cubics.
 */
function parsePathData(d) {
  const tokens =
    d.match(/[MmLlHhVvCcSsQqTtAaZz]|[-+]?(?:\d*\.\d+|\d+)(?:[eE][-+]?\d+)?/g) ?? [];
  const cmds = [];
  let i = 0;
  let cx = 0;
  let cy = 0;
  let sx = 0;
  let sy = 0;
  let prevCubic = null; // last C control point (for S reflection)
  let prevQuad = null; // last Q control point (for T reflection)
  let cmd = null;

  const num = () => {
    const tok = tokens[i];
    i += 1;
    const v = Number(tok);
    if (tok === undefined || !Number.isFinite(v)) {
      throw new Error(`bad number "${tok}" in path "${d}"`);
    }
    return v;
  };
  const flag = () => {
    const tok = tokens[i];
    i += 1;
    if (tok !== "0" && tok !== "1") {
      throw new Error(`bad arc flag "${tok}" in path "${d}" (flags must be space-separated)`);
    }
    return tok === "1";
  };

  while (i < tokens.length) {
    const tok = tokens[i];
    if (/^[A-Za-z]$/.test(tok)) {
      cmd = tok;
      i += 1;
    } else if (cmd === "M") {
      cmd = "L"; // implicit lineto after moveto
    } else if (cmd === "m") {
      cmd = "l";
    } else if (cmd === null || cmd === "Z" || cmd === "z") {
      throw new Error(`unexpected token "${tok}" in path "${d}"`);
    }
    const rel = cmd >= "a" && cmd <= "z";
    const ox = rel ? cx : 0;
    const oy = rel ? cy : 0;
    let keepCubic = false;
    let keepQuad = false;

    switch (cmd.toUpperCase()) {
      case "M": {
        const x = num() + ox;
        const y = num() + oy;
        cmds.push({ c: "M", x, y });
        cx = x;
        cy = y;
        sx = x;
        sy = y;
        break;
      }
      case "L": {
        const x = num() + ox;
        const y = num() + oy;
        cmds.push({ c: "L", x, y });
        cx = x;
        cy = y;
        break;
      }
      case "H": {
        const x = num() + ox;
        cmds.push({ c: "L", x, y: cy });
        cx = x;
        break;
      }
      case "V": {
        const y = num() + oy;
        cmds.push({ c: "L", x: cx, y });
        cy = y;
        break;
      }
      case "C": {
        const x1 = num() + ox;
        const y1 = num() + oy;
        const x2 = num() + ox;
        const y2 = num() + oy;
        const x = num() + ox;
        const y = num() + oy;
        cmds.push({ c: "C", x1, y1, x2, y2, x, y });
        prevCubic = [x2, y2];
        keepCubic = true;
        cx = x;
        cy = y;
        break;
      }
      case "S": {
        const x2 = num() + ox;
        const y2 = num() + oy;
        const x = num() + ox;
        const y = num() + oy;
        const [px1, py1] = prevCubic ? [2 * cx - prevCubic[0], 2 * cy - prevCubic[1]] : [cx, cy];
        cmds.push({ c: "C", x1: px1, y1: py1, x2, y2, x, y });
        prevCubic = [x2, y2];
        keepCubic = true;
        cx = x;
        cy = y;
        break;
      }
      case "Q": {
        const x1 = num() + ox;
        const y1 = num() + oy;
        const x = num() + ox;
        const y = num() + oy;
        cmds.push({ c: "Q", x1, y1, x, y });
        prevQuad = [x1, y1];
        keepQuad = true;
        cx = x;
        cy = y;
        break;
      }
      case "T": {
        const x = num() + ox;
        const y = num() + oy;
        const [x1, y1] = prevQuad ? [2 * cx - prevQuad[0], 2 * cy - prevQuad[1]] : [cx, cy];
        cmds.push({ c: "Q", x1, y1, x, y });
        prevQuad = [x1, y1];
        keepQuad = true;
        cx = x;
        cy = y;
        break;
      }
      case "A": {
        const rx = num();
        const ry = num();
        const rot = num();
        const large = flag();
        const sweep = flag();
        const x = num() + ox;
        const y = num() + oy;
        for (const seg of arcToCubics(cx, cy, rx, ry, rot, large, sweep, x, y)) {
          cmds.push(seg);
        }
        cx = x;
        cy = y;
        break;
      }
      case "Z": {
        cmds.push({ c: "Z" });
        cx = sx;
        cy = sy;
        break;
      }
      default:
        throw new Error(`unsupported path command "${cmd}" in "${d}"`);
    }
    if (!keepCubic) prevCubic = null;
    if (!keepQuad) prevQuad = null;
  }
  return cmds;
}

/** Emit parsed commands as Compose PathBuilder calls (one per line). */
function composePathBody(d, indent) {
  const lines = [];
  for (const cmd of parsePathData(d)) {
    switch (cmd.c) {
      case "M":
        lines.push(`${indent}moveTo(${kf(cmd.x)}, ${kf(cmd.y)})`);
        break;
      case "L":
        lines.push(`${indent}lineTo(${kf(cmd.x)}, ${kf(cmd.y)})`);
        break;
      case "C":
        lines.push(
          `${indent}curveTo(${kf(cmd.x1)}, ${kf(cmd.y1)}, ${kf(cmd.x2)}, ${kf(cmd.y2)}, ${kf(cmd.x)}, ${kf(cmd.y)})`,
        );
        break;
      case "Q":
        lines.push(`${indent}quadTo(${kf(cmd.x1)}, ${kf(cmd.y1)}, ${kf(cmd.x)}, ${kf(cmd.y)})`);
        break;
      case "Z":
        lines.push(`${indent}close()`);
        break;
      default:
        throw new Error(`unknown command ${cmd.c}`);
    }
  }
  return lines;
}

// ---------------------------------------------------------------------------
// naming
